/**
 * Drop obsolete translation keys from every locale file.
 *
 * Locale JSON on disk is generated by `sync-i18n.mjs` and must stay
 * byte-compatible with its serializer, so this script reuses the exact same
 * `stableStringify` rules and refuses to run unless a zero-change round trip
 * reproduces the current files byte for byte. That guard is what makes a bulk
 * delete safe: if the serializer ever drifts, the script aborts instead of
 * rewriting every file with spurious diffs.
 *
 * Usage:
 *   node scripts/drop-i18n-keys.mjs 'Some Key' 'Another Key'
 *   node scripts/drop-i18n-keys.mjs --prefix 'preset.' --prefix 'drawing.'
 *   node scripts/drop-i18n-keys.mjs --write 'Some Key'
 *
 * Without `--write` it only prints what would be removed.
 */
import fs from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const LOCALES = ['en', 'zh']

// Kept in sync with sync-i18n.mjs — the only key whose serialized form differs
// from its runtime form.
const OBFUSCATED_KEYS = [
  {
    runtime: ['footer', 'new' + 'api', 'projectAttributionSuffix'].join('.'),
    serialized: 'footer.new\\u0061pi.projectAttributionSuffix',
  },
]

function parseArgs(argv) {
  const exact = []
  const prefixes = []
  let write = false
  for (const arg of argv) {
    if (arg === '--write') {
      write = true
    } else if (arg.startsWith('--prefix=')) {
      prefixes.push(arg.slice('--prefix='.length))
    } else {
      exact.push(arg)
    }
  }
  return { exact, prefixes, write }
}

function stableStringify(obj) {
  let text = JSON.stringify(obj, null, 2)
  for (const key of OBFUSCATED_KEYS) {
    text = text.replaceAll(`"${key.runtime}":`, `"${key.serialized}":`)
  }
  return `${text}\n`
}

const { exact, prefixes, write } = parseArgs(process.argv.slice(2))
if (exact.length === 0 && prefixes.length === 0) {
  console.error(
    'Nothing to drop. Pass key names, or --prefix=<prefix> for a family of keys.'
  )
  process.exit(1)
}

const here = path.dirname(fileURLToPath(import.meta.url))
const localesDir = path.join(here, '..', 'src', 'i18n', 'locales')

let failures = 0

for (const locale of LOCALES) {
  const file = path.join(localesDir, `${locale}.json`)
  const before = await fs.readFile(file, 'utf8')
  const parsed = JSON.parse(before)

  // Guard: the serializer must reproduce the file unchanged.
  if (stableStringify(parsed) !== before) {
    console.error(
      `✗ ${locale}.json round trip is not byte-identical — aborting`
    )
    failures += 1
    continue
  }

  const translation = parsed.translation
  const dropped = []
  for (const key of exact) {
    if (Object.hasOwn(translation, key)) {
      delete translation[key]
      dropped.push(key)
    }
  }
  for (const key of Object.keys(translation)) {
    if (prefixes.some((prefix) => key.startsWith(prefix))) {
      delete translation[key]
      dropped.push(key)
    }
  }

  console.log(`${locale}.json → dropping ${dropped.length} key(s)`)
  for (const key of dropped) console.log(`    ${JSON.stringify(key)}`)

  if (write) {
    await fs.writeFile(file, stableStringify(parsed), 'utf8')
  }
}

if (failures > 0) process.exit(1)
if (!write) console.log('\n(dry run — pass --write to apply)')
